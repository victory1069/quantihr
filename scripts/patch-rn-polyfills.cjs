#!/usr/bin/env node
/**
 * Compatibility shim: react-native/rn-get-polyfills
 *
 * WHY THIS EXISTS
 * ---------------
 * Expo SDK 57 bundles react-native 0.86.x, which ships a `rn-get-polyfills`
 * entry point. npm resolved 0.87.1 into this workspace instead, and 0.87 deleted
 * that file — the polyfill list moved to `@react-native/js-polyfills`, which
 * react-native still depends on.
 *
 * `@expo/cli` (start/server/metro/withMetroMultiPlatform.js) still calls
 * `require('react-native/rn-get-polyfills')` when bundling for **web**. It wraps
 * that call in a try/catch, but only tolerates MODULE_NOT_FOUND. Because 0.87
 * has an `exports` map that simply does not list the subpath, Node raises
 * ERR_PACKAGE_PATH_NOT_EXPORTED instead, which is rethrown — so the web bundle
 * fails before emitting a single module.
 *
 * Overriding `serializer.getPolyfills` in metro.config.js does NOT fix this:
 * the Expo CLI replaces that function for web after the project config loads.
 *
 * WHAT THIS DOES
 * --------------
 * Recreates the 0.86 entry point as a two-line re-export of the package
 * react-native already depends on, and registers the subpath in the `exports`
 * map so Node will resolve it. Behaviour is identical to upstream 0.86.
 *
 * Idempotent, and a no-op on any react-native that already provides the file.
 *
 * REMOVE THIS when either:
 *   - @expo/cli stops calling the 0.86 entry point, or
 *   - react-native is pinned to the SDK's bundled 0.86.x.
 */

const fs = require('node:fs')
const path = require('node:path')

const SUBPATH = './rn-get-polyfills'
const FILENAME = 'rn-get-polyfills.js'

const SHIM = `/**
 * Generated by scripts/patch-rn-polyfills.cjs — do not edit.
 * Compatibility entry point removed in react-native 0.87; see that script.
 */
'use strict'
module.exports = require('@react-native/js-polyfills')
`

function findReactNative() {
  const candidates = [
    path.resolve(__dirname, '..', 'node_modules', 'react-native'),
    path.resolve(__dirname, '..', 'apps', 'mobile', 'node_modules', 'react-native'),
  ]
  return candidates.filter((dir) => fs.existsSync(path.join(dir, 'package.json')))
}

function patch(rnDir) {
  const pkgPath = path.join(rnDir, 'package.json')
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))

  // Nothing to do on a version that still ships the entry point.
  const filePath = path.join(rnDir, FILENAME)
  const hasFile = fs.existsSync(filePath)
  const hasExport = !!pkg.exports && Object.hasOwn(pkg.exports, SUBPATH)

  if (hasFile && hasExport) {
    return `already patched (react-native ${pkg.version})`
  }

  if (!hasFile) {
    fs.writeFileSync(filePath, SHIM, 'utf8')
  }

  if (pkg.exports && !hasExport) {
    // Insert before the wildcard-free tail so ordering stays readable; Node
    // matches exact subpaths regardless of position, so order is cosmetic.
    pkg.exports[SUBPATH] = `./${FILENAME}`
    fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8')
  }

  return `patched react-native ${pkg.version}`
}

const found = findReactNative()

if (found.length === 0) {
  // react-native is not installed (API-only checkout, CI job that skips mobile).
  console.log('[patch-rn-polyfills] react-native not installed — skipping')
  process.exit(0)
}

for (const dir of found) {
  try {
    console.log(`[patch-rn-polyfills] ${patch(dir)}`)
  } catch (error) {
    console.error(`[patch-rn-polyfills] failed for ${dir}:`, error.message)
    process.exitCode = 1
  }
}
